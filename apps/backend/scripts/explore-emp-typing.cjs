const { chromium } = require("playwright");
const BASE = "https://maxp.online";
const CHROME = "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe";
(async () => {
  const browser = await chromium.launch({ executablePath: CHROME });
  const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
  const page = await ctx.newPage();
  await page.goto(BASE + "/login", { waitUntil: "domcontentloaded" });
  await page.fill("#email", "trial.hr@maxp.test");
  await page.fill("#password", "Maxp@2026");
  await page.click('button[type="submit"]');
  await page.waitForTimeout(9000);
  await page.goto(BASE + "/hr/employees", { waitUntil: "domcontentloaded" });
  await page.waitForTimeout(4500);
  await page.locator('main button:has-text("إضافة موظف")').first().click();
  await page.waitForTimeout(2500);
  const dialogs = await page.locator('[role="dialog"]').count();
  const first = page.locator('[role="dialog"]').last();
  const input = first.locator('input[placeholder="أدخل الاسم الأول"]').first();
  const cnt = await input.count();
  await input.click();
  await input.pressSequentially("سلمى", { delay: 60 });
  const v1 = await input.inputValue();
  await page.keyboard.press("Tab");
  await page.waitForTimeout(600);
  const v2 = await input.inputValue();
  console.log(JSON.stringify({ dialogs, cnt, v1, v2 }));
  await browser.close();
})().catch(e => { console.error("FAILED:", e.message); process.exit(1); });
