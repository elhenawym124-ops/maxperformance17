const { chromium } = require("playwright");
const BASE = "https://maxp.online";
const CHROME = "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe";
(async () => {
  const browser = await chromium.launch({ executablePath: CHROME });
  const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
  const page = await ctx.newPage();
  await page.goto(BASE + "/login", { waitUntil: "domcontentloaded" });
  await page.fill("#email", "trial.hr@maxp.test");
  await page.fill("#password", "Maxp@2026");
  await page.click('button[type="submit"]');
  await page.waitForTimeout(9000);
  await page.goto(BASE + "/hr/departments", { waitUntil: "domcontentloaded" });
  await page.waitForTimeout(4500);
  await page.locator('main button:has-text("إضافة قسم جديد")').first().click();
  await page.waitForTimeout(2500);
  const dlg = page.locator('[role="dialog"]').first();
  const first = dlg.locator("input").first();
  await first.click();
  await first.pressSequentially("قسم ضمان الجودة", { delay: 50 });
  await dlg.locator('button:has-text("إضافة القسم")').first().click();
  await page.waitForTimeout(5000);
  const txt = await page.evaluate(() => (document.querySelector("main")?.innerText || "").replace(/\s+/g, " "));
  console.log(JSON.stringify({ created: txt.includes("قسم ضمان الجودة"), head: txt.slice(0, 120) }, null, 1));
  await page.screenshot({ path: "docs/qa/trial-14d/evidence/46-day2-department-created.png" });
  await browser.close();
})().catch(e => { console.error("FAILED:", e.message); process.exit(1); });
